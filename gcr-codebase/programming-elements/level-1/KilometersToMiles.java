import java.util.*;

public class KilometersToMiles{

    public static void main(String args[]){
	    
		//Creating variable kilometer and assign 10.8 
		double kilometer= 10.8;
		
		
		//Creating variable miles to indicate the kilometers in miles
		double miles= 1.6 * kilometer;
		
		//Display the result
		System.out.println("The Distance "+kilometer+"km in miles "+miles);
	}
}
	    
